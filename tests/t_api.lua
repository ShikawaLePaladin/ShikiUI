-- t_api : detection SuperWoW / Nampower / UnitXP / ClassicAPI, replis sur l'API 1.12, garde-fous.
local SUI = ShikiUI
local A = SUI.Api
BOOT()   -- client nu : aucune extension

local function redetect(extSetup)
  EXT.none()
  if extSetup then extSetup() end
  A.Detect()
  Fire("PLAYER_ENTERING_WORLD")
end

SECTION("t_api : client nu")
redetect()
EQ("superwow", A.superwow, false)
EQ("nampower", A.nampower, false)
EQ("unitxp", A.unitxp, false)
EQ("classic", A.classic, false)
EQ("resume vide", A.Summary(), nil)
EQ("integrations vides", table.getn(A.Integrations()), 0)
EQ("guid indisponible", A.GUID("player"), nil)
EQ("feat.guid", A.feat.guid, false)
EQ("feat.mouseover", A.feat.mouseover, false)
EQ("feat.nameplateGuids", A.feat.nameplateGuids, false)

SECTION("t_api : SuperWoW")
redetect(function() EXT.superwow(true) end)
EQ("superwow detecte", A.superwow, true)
EQ("version", A.swVersion, 1.5)
CONTAINS("resume", A.Summary(), "SuperWoW 1.5")
EQ("guid par UnitExists", A.GUID("player"), "0xP1")
EQ("guid unite absente", A.GUID("target"), nil)
EQ("feat.guid", A.feat.guid, true)
-- detection par les fonctions seules (sans variable de version)
redetect(function() EXT.superwow(true); SUPERWOW_VERSION = nil end)
EQ("detecte via SetAutoloot + SpellInfo", A.superwow, true)
EQ("sans version numerique", A.swVersion, nil)
redetect(function() SetAutoloot = function() end end)
EQ("SetAutoloot seul ne suffit pas", A.superwow, false)
EQ("(nettoyage)", true, true)

SECTION("t_api : Nampower")
redetect(function() EXT.nampower(true, 3) end)
EQ("nampower", A.nampower, true)
EQ("version", A.npVersion, "3.0.1")
EQ("major", A.npMajor, 3)
EQ("guid par GetUnitGUID", A.GUID("player"), "0xP1")
EQ("feat.mouseover", A.feat.mouseover, true)
EQ("feat.spellQueue", A.feat.spellQueue, true)
CONTAINS("resume", A.Summary(), "Nampower 3.0.1")
A.SetMouseover("target")
EQ("SetMouseover transmis", LASTACT(), "Mouseover target")
A.SetMouseover(nil)
EQ("SetMouseover(nil)", LASTACT(), "Mouseover nil")
redetect(function() GetNampowerVersion = function() error("casse") end end)
EQ("GetNampowerVersion qui leve une erreur : non detecte", A.nampower, false)
redetect(function() GetNampowerVersion = function() return nil end end)
EQ("GetNampowerVersion qui ne renvoie rien", A.nampower, false)
redetect(function() EXT.nampower(true); GetUnitGUID = function() error("casse") end end)
EQ("GUID : erreur absorbee", A.GUID("player"), nil)
A.SetMouseover("target")      -- ne plante pas
redetect()
A.SetMouseover("target")      -- sans l'extension : sans effet, ne plante pas

SECTION("t_api : ClassicAPI")
redetect(function() EXT.classic(10501) end)
EQ("classic", A.classic, true)
EQ("version", A.classicVersion, 10501)
EQ("pas de filtre d'unite avant 1.15.0", A.feat.unitEventFilter, false)
EQ("plaques", A.feat.nameplateGuids, true)
redetect(function() EXT.classic(11500) end)
EQ("filtre d'unite des 1.15.0", A.feat.unitEventFilter, true)
redetect(function() CLASSIC_API_VERSION = "1.5" end)
EQ("version non numerique ignoree", A.classic, false)
CONTAINS("resume", (function() EXT.classic(11500); A.Detect(); return A.Summary() end)(), "ClassicAPI 11500")

SECTION("t_api : UnitXP")
redetect(function() EXT.unitxp("real") end)
EQ("unitxp reel", A.unitxp, true)
CONTAINS("resume", A.Summary(), "UnitXP")
EQ("ligne de vue pas encore sure", A.sightSafe, false)
EQ("InSight bloque pendant le delai", A.InSight("target"), nil)
EQ("Behind bloque", A.Behind("target"), nil)
MKTARGET({ dist = 17.4, sight = false, behind = true })
Pump(2)
EQ("encore bloque a 2 s", A.InSight("target"), nil)
Pump(1.5)
EQ("InSight faux", A.InSight("target"), false)
EQ("Behind vrai", A.Behind("target"), true)
EQ("sightSafe", A.sightSafe, true)
W.units.target.sight = true; W.units.target.behind = false
EQ("InSight vrai", A.InSight("target"), true)
EQ("Behind faux", A.Behind("target"), false)
EQ("InSight sans unite", A.InSight("focus"), nil)
-- UnitXP d'origine (experience) : pas de faux positif
redetect(function() EXT.unitxp("vanilla") end)
EQ("UnitXP vanilla : non detecte", A.unitxp, false)
Pump(5)
EQ("InSight sans UnitXP", A.InSight("target"), nil)
redetect(function() EXT.unitxp("greedy") end)
EQ("UnitXP qui repond 1 a tout (horodatage trop petit, inSight non booleen)", A.unitxp, false)
redetect(function() EXT.unitxp("throws") end)
EQ("UnitXP qui leve une erreur", A.unitxp, false)
redetect(function() UnitXP = function(c) if c == "nop" then return true end if c == "version" then return nil end if c == "inSight" then return true end end end)
EQ("sans horodatage mais inSight booleen : detecte", A.unitxp, true)

SECTION("t_api : distance")
-- 1) UnitXP
redetect(function() EXT.unitxp("real") end)
MKTARGET({ dist = 17.4 })
local d, src = A.Distance("target")
NEAR("distance UnitXP", d, 17.4)
EQ("source xp", src, "xp")
EQ("format xp", A.FormatDistance(d, src), "17 yd")
EQ("unite absente", A.Distance("focus"), nil)
-- UnitXP qui echoue a l'usage : repli
UnitXP = function(c) if c == "nop" then return true end if c == "version" then return 1700000000 end error("boum") end
d, src = A.Distance("target")
T("UnitXP en erreur : repli sur les tranches", src == "band")
-- 2) SuperWoW (positions)
redetect(function() EXT.superwow(true) end)
MKTARGET({ pos = { 3, 4, 12 } })
d, src = A.Distance("target")
NEAR("distance par positions (3,4,12 -> 13)", d, 13)
EQ("source pos", src, "pos")
EQ("format pos", A.FormatDistance(d, src), "13 yd")
W.units.target.pos = nil
d, src = A.Distance("target")
T("positions absentes : repli", src == "band")
-- 3) tranches 1.12
redetect()
W.interact = {}
d, src = A.Distance("target"); EQ("hors des deux bandes : nil", d, nil); EQ("source band", src, "band")
EQ("format > 28", A.FormatDistance(d, src), ">28 yd")
W.interact = { target = 4 }
d, src = A.Distance("target"); EQ("10-28", d, 28); EQ("format 10-28", A.FormatDistance(d, src), "10-28 yd")
W.interact = { target = 3 }
d, src = A.Distance("target"); EQ("moins de 10", d, 10); EQ("format < 10", A.FormatDistance(d, src), "<10 yd")
EQ("format sans source", A.FormatDistance(nil, nil), "")
local saved = CheckInteractDistance
CheckInteractDistance = nil
d, src = A.Distance("target"); T("sans CheckInteractDistance", d == nil and src == nil)
CheckInteractDistance = saved

SECTION("t_api : integrations Shiki*")
redetect(function() ShikiwaRotation = {}; ShikaSwap = {}; IsAddOnLoaded = function(n) return n == "ShikiwaHeal" end end)
EQ("integrations", table.concat(A.Integrations(), ","), "ShikiwaRotation,ShikaSwap,ShikiwaHeal")
redetect(function() ShikiwaSignal = {} end)
EQ("signal", table.concat(A.Integrations(), ","), "ShikiwaSignal")
EQ("aucune erreur interne", SUI.errCount, 0)
DONE()
