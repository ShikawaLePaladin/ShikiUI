SECTION("t_castbar : incantation du joueur")
local f = M.bars.player
Fire("SPELLCAST_START", "Fireball", 2000)
EQ("barre active", f.active, true)
EQ("barre visible", f:IsShown(), true)
EQ("nom du sort", f.nameFs:GetText(), "Fireball")
EQ("icone du sort", f.icon.calls.SetTexCoord ~= nil and f.icon.shown, true)
Pump(0.05, 20)
NEAR("la barre se remplit (1 s sur 2)", f.sb:GetValue(), 0.5, 0.06)
T("temps restant ecrit", string.find(f.timeFs:GetText(), "^[01]%.%d$") ~= nil)
T("latence marquee", f.lag.shown)
NEAR("zone de latence proportionnelle", f.lag:GetWidth(), math.floor((0.05 / 2) * f.sbw + 0.5) + 1, 0.01)
local t1b = f.t1
Fire("SPELLCAST_DELAYED", 500)
NEAR("retard : fin repoussee de 0,5 s", f.t1 - t1b, 0.5, 0.001)
Fire("SPELLCAST_STOP")
EQ("fin normale : inactive", f.active, false)
EQ("fin normale : barre pleine", f.sb:GetValue(), 1)
Pump(0.05, 4)
T("fondu en cours", f.fadeAt ~= nil or not f:IsShown())
Pump(0.05, 20)
EQ("fondu termine : cachee", f:IsShown(), false)
-- echec / interruption
Fire("SPELLCAST_START", "Fireball", 2000)
Fire("SPELLCAST_INTERRUPTED")
EQ("interrompue : marquee", f.failed, true)
EQ("interrompue : texte", f.nameFs:GetText(), SUI.L("msg.castbar.interrupted"))
Pump(0.05, 30)
Fire("SPELLCAST_FAILED")
EQ("un echec sans incantation ne fait rien", f.active, false)
Fire("SPELLCAST_START", "Fireball", 2000)
Fire("SPELLCAST_FAILED")
EQ("echec : texte", f.nameFs:GetText(), SUI.L("msg.castbar.failed"))
Pump(0.05, 30)
-- canalisation : arguments (duree, nom)
Fire("SPELLCAST_CHANNEL_START", 3000, "Drain Life")
EQ("canalisation active", f.chan, true)
EQ("canalisation : nom", f.nameFs:GetText(), "Drain Life")
EQ("canalisation : pleine au depart", f.sb:GetValue(), 1)
Pump(0.05, 30)
NEAR("canalisation : se vide (1,5 s sur 3)", f.sb:GetValue(), 0.5, 0.06)
Fire("SPELLCAST_CHANNEL_UPDATE", 600)
NEAR("canalisation raccourcie : 0,6 s restantes", f.t1 - GetTime(), 0.6, 0.001)
NEAR("la duree totale est conservee", f.t1 - f.t0, 3, 0.001)
Fire("SPELLCAST_STOP")
EQ("STOP n'arrete pas une canalisation", f.active, true)
Fire("SPELLCAST_CHANNEL_STOP")
EQ("canalisation terminee", f.active, false)
C.Set("castbar.channeldir", "fill")
Fire("SPELLCAST_CHANNEL_START", 2000, "Drain Life")
EQ("sens rempli : vide au depart", f.sb:GetValue(), 0)
Pump(0.05, 20)
NEAR("sens rempli : moitie", f.sb:GetValue(), 0.5, 0.06)
Fire("SPELLCAST_CHANNEL_STOP")
C.Set("castbar.channeldir", "drain")
Pump(0.05, 30)
-- evenement de fin perdu : la barre se termine seule
Fire("SPELLCAST_START", "Fireball", 1000)
Pump(0.05, 30)
EQ("evenement de fin perdu : terminee seule", f.active, false)
-- les noms inconnus du grimoire n'ont pas d'icone mais ne cassent rien
Fire("SPELLCAST_START", "Sort inconnu", 500)
EQ("sort inconnu : barre quand meme", f.active, true)
EQ("sort inconnu : icone cachee", f.icon.shown, false)
Fire("SPELLCAST_STOP")
Pump(0.05, 30)
EQ("aucune erreur interne", SUI.errCount, 0)

