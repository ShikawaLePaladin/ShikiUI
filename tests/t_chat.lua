SECTION("t_chat : poignees alignees sous echelle (ui.scale et echelle de la fenetre)")
do
  local Mv = SUI.Mover
  ChatFrame1:SetScale(1.25)
  ChatFrame1.left, ChatFrame1.bottom = 80, 60
  C.Set("ui.scale", 0.8)
  M.SyncRelays()
  local rec = Mv.items["chat.main"]
  EQ("echelle du relais = ui.scale", M.mover:GetScale(), 0.8)
  local l, b, r, t, w, h = Mv.Rect(rec)
  NEAR("poignee chat.main : largeur = largeur reelle a l'ecran", w, 400 * 1.25)
  NEAR("poignee chat.main : hauteur = hauteur reelle a l'ecran", h, 120 * 1.25)
  local pt, _, _, x, y = M.mover:GetPoint(1)
  EQ("relais suit la fenetre (point)", pt, "BOTTOMLEFT")
  NEAR("relais suit la fenetre (x, en unites du relais)", x, 80 * 1.25 / 0.8)
  NEAR("relais suit la fenetre (y, en unites du relais)", y, 60 * 1.25 / 0.8)
  -- barre d'onglets : echelle propre (1) differente de celle de la fenetre
  local rb = Mv.items["chat.tabs"]
  local _, _, _, _, wb, hb = Mv.Rect(rb)
  NEAR("poignee chat.tabs : largeur reelle", wb, M.bar:GetWidth() * M.bar:GetScale())
  T("poignee chat.tabs : hauteur au moins celle de la barre", hb >= M.bar:GetHeight() * M.bar:GetScale())
  -- position enregistree : la fenetre est replacee en tenant compte des deux echelles
  C.SetPos("chat.main", 300, 200, 1)
  M.mover.left, M.mover.bottom = 300 / 0.8, 200 / 0.8
  C.Notify("pos", nil)
  local p1, rel1, _, fx, fy = ChatFrame1:GetPoint(1)
  EQ("fenetre 1 replacee", p1, "BOTTOMLEFT")
  NEAR("x = gauche ecran / echelle fenetre", fx, (300 / 0.8) * 0.8 / 1.25)
  NEAR("y = bas ecran / echelle fenetre", fy, (200 / 0.8) * 0.8 / 1.25)
  -- ui.scale change : relais redimensionne, fenetre replacee (plus de poignee decalee)
  C.Set("ui.scale", 1.2)
  EQ("relais a la nouvelle echelle", M.mover:GetScale(), 1.2)
  local _, _, _, _, w2, h2 = Mv.Rect(rec)
  NEAR("apres ui.scale : largeur de la poignee", w2, 400 * 1.25)
  NEAR("apres ui.scale : hauteur de la poignee", h2, 120 * 1.25)
  -- barre detachee : largeur reelle en unites de la barre
  C.SetPos("chat.tabs", 200, 300, 1)
  SUI.Layout.items["chat.tabs"].frame.left, SUI.Layout.items["chat.tabs"].frame.bottom = 200 / 1.2, 300 / 1.2
  C.Notify("pos", nil)
  NEAR("barre detachee : largeur du chat a l'ecran", M.bar:GetWidth() * M.bar:GetScale(), 400 * 1.25)
  -- zone de saisie
  C.SetPos("chat.edit", 120, 60, 1)
  SUI.Layout.items["chat.edit"].frame.left, SUI.Layout.items["chat.edit"].frame.bottom = 120 / 1.2, 60 / 1.2
  C.Notify("pos", nil)
  NEAR("saisie detachee : largeur du chat a l'ecran", ChatFrameEditBox:GetWidth() * ChatFrameEditBox:GetScale(), 400 * 1.25)
  local re = Mv.items["chat.edit"]
  local _, _, _, _, we = Mv.Rect(re)
  NEAR("poignee chat.edit : largeur reelle", we, ChatFrameEditBox:GetWidth() * ChatFrameEditBox:GetScale())
