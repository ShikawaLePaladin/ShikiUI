-- t_cmd : commandes /sui et /shikiui.
local SUI = ShikiUI
local C = SUI.Config
local M = SUI.Menu
BOOT()
SETTLE()

local function cmd(s)
  CHATCLEAR()
  SlashCmdList["SHIKIUI"](s)
  return CHATTEXT()
end

SECTION("t_cmd : aide et inconnues")
local out = cmd("help")
CONTAINS("aide : titre", out, "Commandes ShikiUI")
CONTAINS("aide : profil", out, "/sui profile")
CONTAINS("aide : debug", out, "/sui debug")
local lines = 0
for _ in string.gmatch(out, "\n") do lines = lines + 1 end
local withHelp = 0   -- les alias sans cle d aide (ex. charstats) n ajoutent pas de ligne
for _, n in ipairs(SUI.commandOrder) do if SUI.commands[n] and SUI.commands[n].help then withHelp = withHelp + 1 end end
EQ("aide : 12 lignes + une par commande enregistree avec aide", lines + 1, 12 + withHelp)
CONTAINS("aide : migrate", out, "/sui migrate")
CONTAINS("commande inconnue", cmd("truc"), "Commande inconnue")
CONTAINS("espaces autour", cmd("   help   "), "Commandes ShikiUI")
CONTAINS("casse ignoree", cmd("HELP"), "Commandes ShikiUI")
EQ("nil accepte", pcall(SlashCmdList["SHIKIUI"], ""), true)
M.Hide()

SECTION("t_cmd : menu")
cmd("")
EQ("ouvre", M.frame:IsShown(), true)
cmd("")
EQ("ferme", M.frame:IsShown(), false)
cmd("expert")
EQ("expert = Tout", M.mode, "all")
EQ("expert visible", M.frame:IsShown(), true)
cmd("simple")
EQ("simple = Essentiel", M.mode, "essential")
M.Hide()
cmd("wizard")
EQ("assistant", M.wiz:IsShown(), true)
EQ("etape 1", M.wiz.step, 1)
M.wiz:Hide()

SECTION("t_cmd : status")
out = cmd("status")
CONTAINS("version", out, "ShikiUI 0.3.0")
CONTAINS("extensions", out, "Extensions : aucune")
CONTAINS("integrations", out, "Integrations : aucune")
CONTAINS("profil", out, "Profil : Default")
CONTAINS("langue", out, "langue : fr")
CONTAINS("modules", out, "perf=on")
CONTAINS("modules units", out, "units=on")
CONTAINS("etat UnitXP", out, "UnitXP actif : non")
EXT.unitxp("real"); EXT.superwow(true)
SUI.Api.Detect(); Fire("PLAYER_ENTERING_WORLD")
out = cmd("status")
CONTAINS("extensions detectees", out, "SuperWoW 1.5, UnitXP")
CONTAINS("UnitXP actif", out, "UnitXP actif : oui")
EXT.none(); SUI.Api.Detect(); Fire("PLAYER_ENTERING_WORLD")

SECTION("t_cmd : performance et urgence")
out = cmd("perf")
CONTAINS("rapport", out, "FPS")
CONTAINS("urgence : etat", out, "Mode urgence : inactif")
out = cmd("perf profile on")
CONTAINS("profil actif", out, "Mesure des minuteries activee")
EQ("drapeau", SUI.profile, true)
out = cmd("perf profile off")
CONTAINS("profil coupe", out, "Mesure des minuteries coupee")
EQ("drapeau coupe", SUI.profile, false)
out = cmd("perf reset")
CONTAINS("reset", out, "Compteurs remis a zero")
cmd("emergency on")
EQ("urgence on", SUI.emergency, true)
cmd("emergency off")
EQ("urgence off", SUI.emergency, false)
cmd("emergency")
EQ("urgence bascule", SUI.emergency, true)
cmd("emergency")
EQ("urgence rebascule", SUI.emergency, false)

SECTION("t_cmd : verrouillage")
CONTAINS("unlock", cmd("unlock"), "Mode deplacement")
EQ("mode deplacement actif", SUI.Mover.active, true)
EQ("config", C.Get("ui.locked"), false)
CONTAINS("lock", cmd("lock"), "Interface verrouillee")
EQ("mode deplacement ferme", SUI.Mover.active, false)
EQ("config", C.Get("ui.locked"), true)

SECTION("t_cmd : profils")
CONTAINS("liste", cmd("profile"), "Profils : Default (actif : Default)")
CONTAINS("liste explicite", cmd("profile list"), "Profils : Default")
CONTAINS("creation", cmd("profile new MonProfil"), "Profil cree : MonProfil")
CONTAINS("la casse est conservee", table.concat(C.ListProfiles(), ","), "MonProfil")
C.Set("units.width", 240)
CONTAINS("creation avec copie", cmd("profile new Copie2 Default"), "Profil cree : Copie2")
EQ("copie : valeur", C.db.profiles.Copie2.v["units.width"], 240)
CONTAINS("doublon", cmd("profile new Copie2"), "existe deja")
CONTAINS("nom invalide", cmd("profile new a/b"), "Nom de profil invalide")
CONTAINS("changer", cmd("profile use Copie2"), "Profil actif : Copie2")
EQ("profil actif", C.curName, "Copie2")
CONTAINS("changer vers inconnu", cmd("profile use Nope"), "introuvable")
CONTAINS("supprimer l'actif", cmd("profile delete Copie2"), "Impossible de supprimer le profil actif")
cmd("profile use Default")
CONTAINS("supprimer", cmd("profile delete Copie2"), "Profil supprime : Copie2")
EQ("supprime", C.db.profiles.Copie2, nil)
C.Set("units.width", 200)
CONTAINS("reset", cmd("profile reset"), "Profil reinitialise")
EQ("valeurs remises", C.Get("units.width"), 180)
CONTAINS("sous-commande inconnue : aide", cmd("profile zzz"), "/sui profile")

SECTION("t_cmd : roles")
CONTAINS("role", cmd("role tank"), "Role applique : Tank")
EQ("role actif", C.GetRole(), "tank")
CONTAINS("role pvp", cmd("role PVP"), "Role applique : PvP")
CONTAINS("role inconnu : aide", cmd("role dieu"), "/sui role")
CONTAINS("role vide : aide", cmd("role"), "/sui role")
C.ResetProfile()

SECTION("t_cmd : langue")
CONTAINS("anglais", cmd("lang en"), "Language: en")
EQ("locale", SUI.locale, "en")
CONTAINS("aide en anglais", cmd("help"), "ShikiUI commands")
CONTAINS("francais", cmd("lang fr"), "Langue : fr")
EQ("locale", SUI.locale, "fr")
CONTAINS("langue inconnue : aide", cmd("lang de"), "/sui lang")
EQ("locale inchangee", SUI.locale, "fr")

SECTION("t_cmd : export / import")
C.Set("units.width", 260)
cmd("export")
local str = M.tf.edit:GetText()
EQ("export affiche la chaine", string.sub(str, 1, 5), "SUI1:")
M.tf:Hide()
C.ResetProfile()
out = cmd("import " .. str)
CONTAINS("import direct", out, "Import reussi")
EQ("profil importe", C.db.profiles.Default2.v["units.width"], 260)
out = cmd("import SUI1:00000000:{}")
CONTAINS("import refuse", out, "Import refuse")
cmd("import")
EQ("import sans argument : fenetre", M.tf:IsShown(), true)
M.tf:Hide()

SECTION("t_cmd : debogage")
CONTAINS("debug on", cmd("debug on"), "Debogage actif")
EQ("drapeau", SUI.debug, true)
SUI.Report("test", "erreur factice")
CONTAINS("erreur affichee en debug", CHATTEXT(), "erreur factice")
CONTAINS("debug off", cmd("debug off"), "Debogage coupe")
CHATCLEAR()
SUI.Report("test", "silencieuse")
EQ("silencieux hors debug", CHATTEXT(), "")
cmd("debug")
EQ("bascule", SUI.debug, true)
cmd("debug")
EQ("rebascule", SUI.debug, false)

SECTION("t_cmd : alias")
EQ("commande exposee", SUI.Command, SlashCmdList["SHIKIUI"])
EQ("aucune erreur interne (hors erreur factice)", SUI.errCount, 2)
DONE()
