local function hasHandler(ev, fn)
  local h = SUI.handlers[ev]
  if not h then return false end
  for i = 1, table.getn(h) do if h[i] == fn then return true end end
  return false
end
local function liveTasks(name)
  local n = 0
  for i = 1, table.getn(SUI.tasks) do
    if SUI.tasks[i].name == name and not SUI.tasks[i].dead then n = n + 1 end
  end
  return n
end
local function key(ix) return ix and F.INST[ix][1] or nil end

-- Analyse une annonce et compare les champs donnes.
local function chk(msg, exp)
  local kind, why = F.Parse(msg)
  local P = F.P
  local tag = "[" .. string.sub(msg, 1, 48) .. "] "
  if exp.kind == false then
    T(tag .. "ecartee (" .. tostring(exp.why) .. ")", kind == nil)
    if exp.why then EQ(tag .. "raison", why, exp.why) end
    return
  end
  EQ(tag .. "type", kind, exp.kind)
  if kind == nil then return end
  if exp.inst ~= nil then EQ(tag .. "instance", key(P.i1), exp.inst ~= "" and exp.inst or nil) end
  if exp.inst2 then EQ(tag .. "2e instance", key(P.i2), exp.inst2) end
  if exp.tank then EQ(tag .. "tank", P.tank, exp.tank) end
  if exp.heal then EQ(tag .. "soin", P.heal, exp.heal) end
  if exp.dps then EQ(tag .. "dps", P.dps, exp.dps) end
  if exp.places then EQ(tag .. "places", P.places, exp.places) end
  if exp.lv then EQ(tag .. "niveau", P.lv, exp.lv) end
  if exp.loot then EQ(tag .. "butin", P.loot, exp.loot) end
  if exp.gs then EQ(tag .. "gs", P.gs, exp.gs) end
  if exp.price then EQ(tag .. "prix", P.price, exp.price) end
  if exp.flask then EQ(tag .. "consommables", P.flask, true) end
  if exp.res then EQ(tag .. "resistances", P.res, true) end
end

