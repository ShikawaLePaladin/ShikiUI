  local t = {}
  local ids = BGIDS(0)
  for i = 1, table.getn(ids) do if ids[i] ~= 0 then table.insert(t, ids[i]) end end
  return table.concat(t, ",")
end
local function clearSets()
  for k = 1, 10 do C.SetBase("items.set" .. k, "") end
end
local function hasH(ev, fn)
  local h = SUI.handlers[ev]
  if not h then return false end
  for i = 1, table.getn(h) do if h[i] == fn then return true end end
  return false
end
