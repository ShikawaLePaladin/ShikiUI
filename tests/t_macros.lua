local function casts() return table.concat(MAC.casts, ",") end
local function run(line) MAC_CLEAR(); MAC_RUN(line); return casts() end
local function acts() return table.concat(MAC.acts, ",") end
local function vanilla() return table.concat(MAC.vanilla, ",") end
local function reset()
  MAC_CLEAR()
