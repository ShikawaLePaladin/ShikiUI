SECTION("t_macros : detection d'un addon equivalent")
rawset(_G, "CleveRoids", {})
CHATCLEAR()
C.Set("modules.macros", true)
EQ("module actif", mod.enabled, true)
EQ("conflit detecte", M.conflict, "CleveRoids")
EQ("aucune execution", M.exec, false)
T("gestionnaire CAST intact", SlashCmdList.CAST == origCast)
CONTAINS("message clair", CHATTEXT(), "CleveRoids est charge")
reset()
EQ("rien n'est lance par ce module", run("/cast [mod:shift] Fireball"), "")
EQ("la ligne va a l'autre addon (gestionnaire d'origine)", vanilla(), "CAST|[mod:shift] Fireball")
CHATCLEAR()
SlashCmdList["SHIKIUI"]("macros check /cast [mod:shift] Fireball")
CONTAINS("l'aide a la verification reste disponible", CHATTEXT(), "Valide")
CHATCLEAR()
SlashCmdList["SHIKIUI"]("macros")
CONTAINS("statut : retrait", CHATTEXT(), "se met en retrait")
C.Set("modules.macros", false)
rawset(_G, "CleveRoids", nil)
rawset(_G, "IsAddOnLoaded", function(n) return n == "SuperCleveRoidMacros" and 1 or nil end)
C.Set("modules.macros", true)
EQ("conflit via IsAddOnLoaded", M.conflict, "SuperCleveRoidMacros")
C.Set("modules.macros", false)
rawset(_G, "IsAddOnLoaded", function(n) return n == "CleverMacro" and 1 or nil end)
C.Set("modules.macros", true)
EQ("conflit CleverMacro", M.conflict, "CleverMacro")
C.Set("modules.macros", false)
rawset(_G, "IsAddOnLoaded", nil)
EQ("plus de conflit", M.DetectConflict(), nil)
-- SuperMacro : signale mais ne bloque pas
rawset(_G, "SuperMacro_RunMacro", function() end)
CHATCLEAR()
C.Set("modules.macros", true)
EQ("SuperMacro n'est pas un conflit", M.conflict, nil)
EQ("SuperMacro signale", M.warnSM, true)
CONTAINS("message SuperMacro", CHATTEXT(), "SuperMacro detecte")
T("execution active malgre SuperMacro", M.exec)
C.Set("modules.macros", false)
rawset(_G, "SuperMacro_RunMacro", nil)
M.warnSM = false
M.smShown = nil
EQ("erreurs internes", SUI.errCount, 0)

