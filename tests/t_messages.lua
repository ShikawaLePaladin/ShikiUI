local function liveTasks(name)
  local n = 0
  for i = 1, table.getn(SUI.tasks) do
    if SUI.tasks[i].name == name and not SUI.tasks[i].dead then n = n + 1 end
  end
  return n
end
local function hasHandler(ev, fn)
  local h = SUI.handlers[ev]
  if not h then return false end
  for i = 1, table.getn(h) do if h[i] == fn then return true end end
  return false
end
local function shownToasts()
  local n = 0
  for i = 1, 5 do if M.tf[i]:IsShown() then n = n + 1 end end
  return n
end
local function store()
  return ShikiUIDB.global.msghist[C.CharKey()]
end
local function reset()
  for i = 1, 8 do
    if M.win[i] and M.win[i].conv then M.CloseSlot(i) end
  end
  M.ClearToasts()
  for k, _ in pairs(M.convs) do M.convs[k] = nil end
  M.nconv = 0
  M.HistClear(nil)
  for i = table.getn(MSGW.sent), 1, -1 do MSGW.sent[i] = nil end
  for i = table.getn(MSGW.sounds), 1, -1 do MSGW.sounds[i] = nil end
  for i = table.getn(MSGW.chatEv), 1, -1 do MSGW.chatEv[i] = nil end
  for k, _ in pairs(M.replied) do M.replied[k] = nil end
  M.nreplied = 0
  for k, _ in pairs(M.kwSeen) do M.kwSeen[k] = nil end
  M.nseen = 0
  C.Set("messages.autoopen", true)
  C.Set("messages.toast", true)
  C.Set("messages.mode", "windows")
  C.Set("messages.suppress", true)
  C.Set("messages.combatqueue", true)
  C.Set("messages.autoreply", false)
  C.Set("messages.history", true)
  C.Set("messages.maxwin", 4)
  C.Set("messages.histper", 100)
  C.Set("messages.histtotal", 1500)
  C.Set("messages.toastsecs", 10)
  C.Set("messages.preload", 8)
  C.Set("messages.openonsend", true)
  MSGW.afk, MSGW.dnd = false, false
  W.combat = false
  SETTLE(3)
end

