local function hasHandler(ev, fn)
  local h = SUI.handlers[ev]
  if not h then return false end
  for i = 1, table.getn(h) do if h[i] == fn then return true end end
  return false
end
local function ent(seg, kind, name) return seg and seg.k[kind][name] end
local function tot(seg, kind, name) local e = ent(seg, kind, name); return e and e.total or 0 end
local function sp(seg, kind, name, spell) local e = ent(seg, kind, name); return e and e.sp[spell] or 0 end
local function crits(seg, kind, name, spell) local e = ent(seg, kind, name); return e and e.hc[spell] or 0 end

