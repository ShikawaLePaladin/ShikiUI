  C.Set("meter.windows", 1)
  SETTLE()

  -- migration des anciens reglages : meter.show = false => toutes fermees
  C.Set("modules.meter", false)
  C.cur.v["meter.show"] = false
  C.cur.mm = C.cur.mm or {}
  C.cur.mm.raid = C.cur.mm.raid or {}
  C.cur.mm.raid["meter.show"] = false
  C.Set("modules.meter", true)
  SETTLE()
  for n = 1, 4 do EQ("migration : fenetre " .. n .. " fermee", C.Get("meter.open" .. n), false) end
  EQ("migration : ancienne cle effacee", C.cur.v["meter.show"], nil)
  EQ("migration : ancienne cle effacee (raid)", C.cur.mm.raid["meter.show"], nil)
  EQ("migration : mode raid ferme aussi", C.GetIn("raid", "meter.open1"), false)
  EQ("migration : endormi", M.awake, false)
  EQ("migration : fenetre cachee", M.win[1].f:IsShown(), false)
  cmd("meter show")
  EQ("migration : rouvrable", M.win[1].f:IsShown(), true)
  C.Set("meter.windows", 2)
  SETTLE()
  EQ("fenetre ajoutee par le reglage : ouverte", C.Get("meter.open2"), true)
  EQ("fenetre ajoutee par le reglage : visible", M.win[2].f:IsShown(), true)
  C.Set("meter.windows", 1)
  SETTLE()
  -- ancien show = true : rien de ferme
  C.Set("modules.meter", false)
  C.cur.v["meter.show"] = true
  C.Set("modules.meter", true)
  SETTLE()
  EQ("migration show=true : ouverte", C.Get("meter.open1"), true)
  EQ("migration show=true : cle effacee", C.cur.v["meter.show"], nil)
  W.combat = false

  -- Menace : alimentee tant qu'une fenetre du compteur est ouverte (vue menace dans la fenetre 2, fenetre 1 fermee)
  local TH = SUI.Threat
  local mt = SUI.modules.threat
  C.Set("threat.show", false)
  C.Set("modules.threat", true)
  SETTLE()
  EQ("menace : module actif", mt.enabled, true)
  EQ("menace : sa propre fenetre fermee => dort", TH.running and true or false, false)
  C.Set("meter.windows", 2)
  C.Set("meter.view2", "threat")
  SETTLE()
  EQ("menace : fenetre 2 en vue menace => alimentee", TH.running and true or false, true)
  W.combat = true
  MKTARGET({ name = "Orc", level = 60 })
  NOW = 7000
  C.Set("meter.open1", false)
  EQ("menace : fenetre 1 fermee, fenetre 2 ouverte => meter eveille", M.awake, true)
  EQ("menace : toujours alimentee", TH.running and true or false, true)
  MET_FIRE(SD, ORC, BOB, 133, 250, 0, 0)
  T("menace : l'estimation recoit les degats", (TH.est["Orc"] and TH.est["Orc"]["Bob"] or 0) > 0)
  C.Set("meter.open2", false)
  EQ("menace : tout ferme => meter endormi", M.awake, false)
  EQ("menace : tout ferme => menace endormie", TH.running and true or false, false)
  C.Set("meter.open2", true)
  EQ("menace : fenetre 2 rouverte => alimentee", TH.running and true or false, true)
  C.Set("meter.open1", true)
  C.Set("meter.view2", "heal")
  EQ("menace : plus de vue menace => plus alimentee", TH.running and true or false, false)
  C.Set("meter.view2", "threat")
  EQ("menace : vue menace remise => alimentee", TH.running and true or false, true)
  C.Set("threat.show", true)
  C.Set("meter.view2", "heal")
  EQ("menace : sa propre fenetre ouverte => reste alimentee", TH.running and true or false, true)
  C.Set("threat.show", false)
  EQ("menace : plus aucun client => dort", TH.running and true or false, false)
  C.Set("modules.threat", false)
  C.Set("meter.windows", 1)
  SETTLE()
  W.combat = false

  -- le bouton de remise a zero ne s'appelle plus X
  EQ("remise a zero : libelle distinct", M.win[1].bReset.label:GetText(), "C")
  EQ("fermeture : libelle x", M.win[1].bClose.label:GetText(), "x")
end

