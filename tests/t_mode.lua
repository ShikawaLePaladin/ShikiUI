-- t_mode : modes de jeu Normal / Raid (Mode.lua + couches de Config.lua) : bascule, priorites de fusion, automatique, addons externes.
local SUI = ShikiUI
local C = SUI.Config
local M = SUI.Mode
BOOT()
SETTLE()

SECTION("t_mode : etat initial")
EQ("mode au demarrage", C.mode, "normal")
EQ("Mode.Current", M.Current(), "normal")
EQ("autre mode", M.Other(), "raid")
EQ("modes declares", table.concat(C.modeOrder, ","), "normal,raid")
T("mode.auto coupe par defaut", C.Get("mode.auto") == false)
EQ("aucun ecart enregistre", next(C.cur.mm), nil)

SECTION("t_mode : bascule manuelle")
local ok, key = M.Set("raid", "manual")
EQ("Set raid accepte", ok, true)
EQ("message", key, "msg.mode.switched")
EQ("mode raid", C.mode, "raid")
EQ("pas d'automatique", M.autoSet, false)
EQ("preset livre applique en Raid", C.Get("units.smooth"), false)
EQ("profil intact", C.cur.v["units.smooth"], nil)
EQ("memorise", ShikiUIDB.modes[C.CharKey()].m, "raid")
ok, key = M.Set("pirate", "manual")
EQ("mode inconnu refuse", ok, false)
EQ("message mode inconnu", key, "msg.mode.bad")
M.Set("normal", "manual")
EQ("retour Normal", C.mode, "normal")
EQ("preset non applique en Normal", C.Get("units.smooth"), true)
EQ("memoire effacee en Normal", ShikiUIDB.modes[C.CharKey()], nil)
local r = M.Toggle()
EQ("toggle -> raid", C.mode, "raid")
M.Toggle()
EQ("toggle -> normal", C.mode, "normal")

SECTION("t_mode : ecarts de l'utilisateur propres au mode")
M.Set("raid", "manual")
C.Set("units.width", 220)
EQ("ecrit dans le mode Raid", C.cur.mm.raid["units.width"], 220)
EQ("profil intact", C.cur.v["units.width"], nil)
EQ("lu en Raid", C.Get("units.width"), 220)
EQ("couche source", C.Source("units.width"), "override")
T("modifie dans la couche courante", C.IsModified("units.width"))
M.Set("normal", "manual")
T("Normal inchange", C.Get("units.width") ~= 220)
EQ("GetIn raid", C.GetIn("raid", "units.width"), 220)
M.Set("raid", "manual")
C.Set("units.smooth", true)
EQ("l'utilisateur gagne sur le preset", C.Get("units.smooth"), true)
C.Reset("units.smooth")
EQ("reset : retour au preset livre", C.Get("units.smooth"), false)
C.Set("units.smooth", false)
EQ("valeur egale au preset : pas d ecart enregistre", C.IsModified("units.smooth"), false)
C.Reset("units.width")
T("reset : retour au profil", C.Get("units.width") ~= 220)
C.Set("units.width", 210)
EQ("ResetMode", C.ResetMode("raid"), true)
T("ecarts effaces", C.Get("units.width") ~= 210)
EQ("ResetMode normal refuse", C.ResetMode("normal"), false)
EQ("ResetMode inconnu refuse", C.ResetMode("zzz"), false)
M.Set("normal", "manual")
C.SetBase("units.width", 150)
EQ("SetBase ecrit toujours dans le profil", C.cur.v["units.width"], 150)
M.Set("raid", "manual")
C.SetBase("units.width", 160)
EQ("SetBase en Raid : profil aussi", C.cur.v["units.width"], 160)
EQ("lu en Raid (sans ecart)", C.Get("units.width"), 160)
M.Set("normal", "manual")
C.Reset("units.width")

SECTION("t_mode : priorite des presets (ecart > role+classe > classe > role > generique > profil > defaut)")
local def = C.defaults["units.width"]
M.Set("raid", "manual")
EQ("defaut", C.Get("units.width"), def)
C.class = "PALADIN"
C.ApplyRole("tank")
C.AddPreset("raid", "*", { ["units.width"] = 100 })
EQ("generique", C.Get("units.width"), 100)
EQ("source generique", C.Source("units.width"), "preset")
C.AddPreset("raid", "tank", { ["units.width"] = 120 })
EQ("role bat generique", C.Get("units.width"), 120)
C.AddPreset("raid", "PALADIN", { ["units.width"] = 130 })
EQ("classe bat role", C.Get("units.width"), 130)
C.AddPreset("raid", "tank/PALADIN", { ["units.width"] = 140 })
EQ("role+classe bat classe", C.Get("units.width"), 140)
C.Set("units.width", 220)
EQ("ecart bat tout", C.Get("units.width"), 220)
C.Reset("units.width")
C.ApplyRole("dps")
EQ("autre role : la classe tient", C.Get("units.width"), 130)
C.class = "WARRIOR"
C.RebuildPresets()
EQ("autre classe et role : generique", C.Get("units.width"), 100)
C.ApplyRole("tank")
EQ("role tank, classe guerrier", C.Get("units.width"), 120)
M.Set("normal", "manual")
EQ("Normal ignore tous les presets", C.Get("units.width"), def)
C.SetBase("units.width", 175)
M.Set("raid", "manual")
EQ("preset bat le profil", C.Get("units.width"), 120)
M.Set("normal", "manual")
EQ("profil en Normal", C.Get("units.width"), 175)
C.Reset("units.width")

SECTION("t_mode : presets invalides et modules 'raid = off'")
EQ("preset normal refuse", C.AddPreset("normal", "*", { ["units.width"] = 1 }), false)
EQ("mode inconnu refuse", C.AddPreset("zzz", "*", { ["units.width"] = 1 }), false)
EQ("spec inconnue refusee", C.AddPreset("raid", "NOPE", { ["units.width"] = 1 }), false)
EQ("role/classe inconnu refuse", C.AddPreset("raid", "tank/NOPE", { ["units.width"] = 1 }), false)
EQ("table absente refusee", C.AddPreset("raid", "*", nil), false)
EQ("cle inconnue acceptee a l'ajout", C.AddPreset("raid", "*", { ["nokey.x"] = 1, ["units.hptext"] = "nimporte" }), true)
T("cles invalides signalees", C.presetBad["raid:nokey.x"] and C.presetBad["raid:units.hptext"])
M.Set("raid", "manual")
EQ("choix invalide sans effet", C.Get("units.hptext"), C.GetIn("normal", "units.hptext"))
M.Set("normal", "manual")
SUI.RegisterModule("zzraid", { cost = "light", raid = "off", options = {} })
SUI.EnableModule("zzraid")
EQ("module 'raid off' actif en Normal", C.Get("modules.zzraid"), true)
EQ("module actif", SUI.modules.zzraid.enabled, true)
M.Set("raid", "manual")
EQ("module coupe en Raid", C.Get("modules.zzraid"), false)
EQ("module coupe pour de bon", SUI.modules.zzraid.enabled, false)
local tbl = M.ModuleTable()
local found
for i = 1, table.getn(tbl) do if tbl[i].name == "zzraid" then found = tbl[i] end end
EQ("table des modules : Normal", found.normal, true)
EQ("table des modules : Raid", found.raid, false)
EQ("table des modules : cout", found.cost, "light")
C.Set("modules.zzraid", true)
EQ("l'utilisateur peut le garder en Raid", SUI.modules.zzraid.enabled, true)
M.Set("normal", "manual")
EQ("retour Normal : toujours actif", SUI.modules.zzraid.enabled, true)
C.ResetMode("raid")

local notified = 0
C.Watch("", function(k) if k == nil then notified = notified + 1 end end)
M.Set("normal", "manual")
EQ("meme mode : aucune notification generale", notified, 0)
M.Set("raid", "manual")
EQ("changement de mode : une notification generale", notified, 1)
M.Set("normal", "manual")

SECTION("t_mode : combat")
W.combat = true
ok, key = M.Set("raid", "manual")
EQ("accepte", ok, true)
EQ("mis en attente", key, "msg.mode.queued")
EQ("pas de bascule en combat", C.mode, "normal")
EQ("demande retenue", M.queued, "raid")
M.Set("normal", "manual")
EQ("derniere demande gagne", M.queued, "normal")
M.Set("raid", "manual")
W.combat = false
Fire("PLAYER_REGEN_ENABLED")
EQ("applique a la sortie du combat", C.mode, "raid")
EQ("file vide", M.queued, nil)
M.Set("normal", "manual")

SECTION("t_mode : bascule automatique")
LEAVERAID()
C.Set("mode.auto", true)
EQ("evenements ecoutes", M.events, true)
Fire("PLAYER_ENTERING_WORLD")
EQ("rien a faire hors raid", C.mode, "normal")
INRAID("raid", 10)
Fire("PLAYER_ENTERING_WORLD")
EQ("entree en raid", C.mode, "raid")
EQ("mis par l'automatique", M.autoSet, true)
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
EQ("retour differe", C.mode, "raid")
Pump(5)
EQ("pas avant le delai", C.mode, "raid")
Pump(6)
EQ("retour automatique", C.mode, "normal")
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
Pump(15)
EQ("retour dans le raid avant le delai : on reste", C.mode, "raid")
-- choix manuel : l'automatique ne le defait pas
M.Set("normal", "manual")
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
EQ("situation inchangee : le choix manuel tient", C.mode, "normal")
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
M.Set("raid", "manual")
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
Pump(30)
EQ("Raid choisi a la main : jamais defait par l'automatique", C.mode, "raid")
M.Set("normal", "manual")
-- declencheurs
C.Set("mode.trigger", "instance")
