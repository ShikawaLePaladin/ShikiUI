Fire("RAID_ROSTER_UPDATE")
EQ("declencheur instance : groupe seul ignore", C.mode, "normal")
INRAID("raid", 0)
Fire("RAID_ROSTER_UPDATE")
EQ("declencheur instance : instance de raid", C.mode, "raid")
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
Pump(12)
EQ("retour", C.mode, "normal")
C.Set("mode.trigger", "group")
INRAID("raid", 0)
Fire("RAID_ROSTER_UPDATE")
EQ("declencheur groupe : instance seule ignoree", C.mode, "normal")
INRAID(nil, 5)
Fire("RAID_ROSTER_UPDATE")
EQ("declencheur groupe : groupe de raid", C.mode, "raid")
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
Pump(12)
C.Set("mode.trigger", "both")
INRAID("pvp", 20)
Fire("PLAYER_ENTERING_WORLD")
EQ("champ de bataille : pas de mode Raid", C.mode, "normal")
LEAVERAID()
Fire("PLAYER_ENTERING_WORLD")
-- delai nul
C.Set("mode.delay", 0)
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
LEAVERAID()
Fire("RAID_ROSTER_UPDATE")
EQ("delai 0 : retour immediat", C.mode, "normal")
C.Set("mode.delay", 10)
-- coupe : plus d'ecoute
C.Set("mode.auto", false)
EQ("evenements detaches", M.events, false)
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
EQ("automatique coupe : rien", C.mode, "normal")
LEAVERAID()

SECTION("t_mode : memoire entre les sessions")
C.Set("mode.auto", false)
LEAVERAID()
M.Set("raid", "manual")
C.mode = "normal"
M.Boot()
EQ("mode relu au demarrage", C.mode, "raid")
EQ("choix manuel relu", M.autoSet, false)
M.Set("normal", "manual")
C.Set("mode.auto", true)
INRAID("raid", 10)
Fire("RAID_ROSTER_UPDATE")
EQ("auto : memorise comme automatique", ShikiUIDB.modes[C.CharKey()].auto, true)
C.mode = "normal"
M.autoSet = false
M.Boot()
EQ("automatique relu", M.autoSet, true)
EQ("raid relu", C.mode, "raid")
C.Set("mode.auto", false)
LEAVERAID()
ShikiUIDB.modes[C.CharKey()] = { m = "pirate" }
M.Boot()
EQ("memoire corrompue : Normal", C.mode, "normal")
ShikiUIDB.modes = "n'importe quoi"
M.Boot()
EQ("table de modes corrompue : Normal", C.mode, "normal")
C.Set("mode.auto", false)
LEAVERAID()
M.Set("normal", "manual")

