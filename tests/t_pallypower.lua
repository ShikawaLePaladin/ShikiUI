-- t_pallypower : module "pallypower" (grille d'attributions, cycle de benediction, fenetre, commandes, cycle de vie).
local SUI = ShikiUI
local C = SUI.Config
PP_RAID({})
PP_SETUP()
EXT.unitxp("real")
BOOT()
SETTLE()
W.units.player.class = "PALADIN"

SECTION("t_pallypower : enregistrement et contrat")
local M = SUI.PallyPower
local mod = SUI.modules.pallypower
T("module enregistre", mod ~= nil)
EQ("cout declare", mod and mod.cost, "medium")
T("coupe par defaut", not mod.enabled)
EQ("categorie du menu", SUI.categories.pallypower, 68)
T("options declarees : greater", C.meta["pallypower.greater"] ~= nil)
T("options declarees : judge", C.meta["pallypower.judge"] ~= nil)
EQ("greater par defaut", C.Get("pallypower.greater"), true)
EQ("5 benedictions en grille", table.getn(M.BLESS), 5)
EQ("aucune erreur interne au demarrage", SUI.errCount, 0)

SECTION("t_pallypower : attributions et memoire")
C.Set("modules.pallypower", true)
SETTLE()
EQ("active via le socle", mod.enabled, true)
M.assign = {}
M.Toggle("Bob", "kings")
EQ("toggle : attribuee", M.Has("Bob", "kings"), true)
M.Toggle("Bob", "kings")
EQ("toggle : retiree", M.Has("Bob", "kings"), false)
M.Toggle("Bob", "kings", true)
EQ("toggle : forcee", M.Has("Bob", "kings"), true)
T("memoire persistee (global)", type(C.GetGlobal("pallypower.assign")) == "table" and C.GetGlobal("pallypower.assign").Bob ~= nil)

SECTION("t_pallypower : liste du raid")
PP_RAID({ "Bob/WARRIOR", "Eve/MAGE", "Shikiwa/PALADIN", "Bob/WARRIOR" })
Fire("RAID_ROSTER_UPDATE")
SETTLE()
EQ("3 membres (le doublon filtre)", M.nrost, 3)
EQ("ordre du raid : 1", M.roster[1].name, "Bob")
EQ("classe EN lue de la var 6", M.roster[1].file, "WARRIOR")
EQ("classe paladin", M.roster[3].file, "PALADIN")
local nc = 0
for _ in pairs(M.classes) do nc = nc + 1 end
EQ("3 classes presentes", nc, 3)
-- groupe (pas de raid) : le joueur + party1..n
PP_PARTY({ "Lia/PRIEST" })
Fire("PARTY_MEMBERS_CHANGED")
SETTLE()
EQ("groupe : joueur + 1", M.nrost, 2)
EQ("groupe : le joueur d'abord", M.roster[1].name, "Shikiwa")
EQ("groupe : party1", M.roster[2].name, "Lia")
PP_RAID({ "Bob/WARRIOR", "Eve/MAGE", "Shikiwa/PALADIN" })
Fire("RAID_ROSTER_UPDATE")
SETTLE()

SECTION("t_pallypower : boutons de classe et tout le monde")
M.ClearAll()
M.SetClass("WARRIOR", true)
T("jeu guerrier : kings", M.Has("Bob", "kings"), true)
T("jeu guerrier : might", M.Has("Bob", "might"), true)
EQ("jeu guerrier : pas les autres", M.Has("Bob", "wisdom"), false)
M.SetAll("kings", true)
EQ("tous : kings", M.Has("Eve", "kings"), true)
EQ("tous : tout le monde l'a", M.AllHave("kings"), true)
M.SetAll("kings", false)
EQ("retire : plus personne", M.AllHave("kings"), false)
M.SetClass("MAGE", true)
T("jeu mage : wisdom", M.Has("Eve", "wisdom"), true)
M.SetClass("MAGE", false)
EQ("clic droit : classe videe", M.Has("Eve", "wisdom"), false)
M.SetClass("WARRIOR", false)
EQ("guerrier vide", M.Has("Bob", "might"), false)
M.ClearAll()
EQ("tout vide", M.Has("Bob", "kings"), false)

SECTION("t_pallypower : cycle (SuperWoW, lancement direct)")
EXT.superwow(true)
SUI.Api.Detect()
M.SetAll("kings", true)
PP_CLEARCASTS()
CHATCLEAR()
M.CastAll()
T("cycle demarre", M.task ~= nil)
CONTAINS("jugement none : rien sur la cible", PP_CASTS(), "")
Pump(1.2, 6)
EQ("tout pose en un seul tour (3 joueurs)", M.npairs, 0)
Pump(1.2)
Pump(1.2)
Pump(1.2, 6)
for i = 1, table.getn(SUI.tasks) do local t = SUI.tasks[i] print("  " .. t.name .. " next=" .. math.floor(t.nextAt*10)/10 .. " every=" .. t.interval .. " dead=" .. tostring(t.dead)) end
print("DBG casts=" .. PP_CASTS())
CONTAINS("3 grandes benedictions posees", PP_CASTS(), "Ben\195\169diction sup\195\169rieure des Rois->raid1")
CONTAINS("raid2 benie", PP_CASTS(), "Ben\195\169diction sup\195\169rieure des Rois->raid2")
CONTAINS("raid3 benie", PP_CASTS(), "Ben\195\169diction sup\195\169rieure des Rois->raid3")
CONTAINS("message de fin", CHATTEXT(), "3")
-- plus rien a faire : tout est deja pose
CHATCLEAR()
PP_BUFF("raid1", "Greater Blessing of Kings")
PP_BUFF("raid2", "Greater Blessing of Kings")
PP_BUFF("raid3", "Greater Blessing of Kings")
M.CastAll()
EQ("deja benis : aucune pose", M.npairs, 0)
CONTAINS("tout le monde a ses bene", CHATTEXT(), "deja ses")
-- simple : noms SANS Greater, et ceux qui l'ont en greater sont SAUTES (jamais de re-pose)
C.Set("pallypower.greater", false)
PP_BUFF("raid1", "Greater Blessing of Kings")
PP_BUFF("raid2", "Greater Blessing of Kings")
PP_BUFF("raid3", nil)
PP_CLEARCASTS()
M.CastAll()
Pump(1.2, 6)
EQ("greater tient lieu de simple : seul raid3 est repose", table.getn(PP.casts), 1)
CONTAINS("simple pour le manquant", PP_CASTS(), "Ben\195\169diction des Rois->raid3")
PP_BUFF("raid3", "Blessing of Kings")
C.Set("pallypower.greater", true)

SECTION("t_pallypower : progressif, mort, jugement")
M.ClearAll()
M.SetAll("kings", true)
M.SetAll("wisdom", true)
-- wisdom posee sur tout le monde : ne compte que kings a poser (3), puis un second passage
for i = 1, 3 do PP_BUFF("raid" .. i, "Greater Blessing of Wisdom") end
PP_CLEARCASTS()
M.CastAll()
EQ("3 poses en file", M.npairs, 3)
M.Stop()
M.ClearAll()
-- mort : le joueur mort en pause, les cibles mortes sautees
PP.dead.player = true
M.SetAll("kings", true)
PP_CLEARCASTS()
M.CastAll()
Pump(0.6, 2)
EQ("joueur mort : rien pose", table.getn(PP.casts), 0)
PP.dead.player = false
Pump(1.2, 4)
T("reveille : le cycle a repris", table.getn(PP.casts) >= 1)
M.Stop()
PP_CLEARCASTS()
M.ClearAll()
-- cible morte dans la file : sautee (Bob mort, Eve vivante)
M.Toggle("Bob", "kings", true)
M.Toggle("Eve", "kings", true)
PP.dead.raid1 = true
PP_CLEARCASTS()
M.CastAll()
Pump(1.2, 6)
CONTAINS("cible morte sautee : Eve benie", PP_CASTS(), "raid2")
EQ("un seul cast pour une cible morte", table.getn(PP.casts), 1)
PP.dead.raid1 = false
M.Stop()
M.ClearAll()
-- jugement sur un ennemi au demarrage
C.Set("pallypower.judge", "light")
PP.hostile = true
M.SetAll("kings", true)
PP_BUFF("raid1", "Greater Blessing of Kings")
PP_BUFF("raid2", "Greater Blessing of Kings")
PP_BUFF("raid3", "Greater Blessing of Kings")
PP_CLEARCASTS()
M.CastAll()
CONTAINS("jugement de lumiere pose", PP_CASTS(), "Jugement de Lumi\195\168re")
C.Set("pallypower.judge", "none")
PP.hostile = false
M.ClearAll()
-- module coupe : refus propre
C.Set("modules.pallypower", false)
SETTLE()
CHATCLEAR()
M.CastAll()
print("DBGE on=" .. tostring(M.on) .. " chat=[" .. CHATTEXT() .. "]")
CONTAINS("module coupe : message", CHATTEXT(), "pp")
C.Set("modules.pallypower", true)
SETTLE()

SECTION("t_pallypower : fenetre et grille")
M.Open()
SETTLE()
T("fenetre ouverte", M.win ~= nil and M.win:IsShown())
T("poignee de deplacement", SUI.Layout.items["pp.win"] ~= nil)
T("engrenage", M.win.suiGears ~= nil and table.getn(M.win.suiGears) >= 1)
EQ("lignes visibles", M.view, 22)
T("ligne 1 : Bob", M.win.rows[1]._n, "Bob")
T("case kings rattachee a Bob", M.win.rows[1].cells.kings.who, "Bob")
-- atelier d'attribution : la case est rattachee a son joueur
local cell = M.win.rows[1].cells.kings
M.Toggle(cell.who, cell.bless, true)
T("case rattachee au joueur de la ligne", cell.who, "Bob")
T("case accentuee = attribuee", M.Has("Bob", "kings"), true)
-- molette : defilement borne
M.Scroll(5)
EQ("defilement borne au roster", M.offset, 0)
-- plus de 22 membres : le defilement avance
local big = {}
for i = 1, 30 do big[i] = "Membre" .. i .. "/WARRIOR" end
PP_RAID(big)
Fire("RAID_ROSTER_UPDATE")
SETTLE()
EQ("30 membres", M.nrost, 30)
M.Scroll(3)
EQ("defilement avance", M.offset, 3)
M.Scroll(-10)
EQ("defilement borne a zero", M.offset, 0)
-- plafond de la liste : la grille ne prepare que 40 lignes
local big = {}
for i = 1, 45 do big[i] = "Sur" .. i .. "/WARRIOR" end
PP_RAID(big)
Fire("RAID_ROSTER_UPDATE")
SETTLE()
EQ("liste plafonnee a 40", M.nrost, 40)
M.Close()
EQ("fermee", M.win:IsShown(), false)

SECTION("t_pallypower : commandes")
PP_RAID({ "Bob/WARRIOR", "Eve/MAGE" })
Fire("RAID_ROSTER_UPDATE")
SETTLE()
M.Open()
SETTLE()
SlashCmdList["SHIKIUI"]("pp close")
EQ("/sui pp close", M.win:IsShown(), false)
SlashCmdList["SHIKIUI"]("pp")
SETTLE()
EQ("/sui pp (ouvre)", M.win:IsShown(), true)
SlashCmdList["SHIKIUI"]("pp clear")
EQ("/sui pp clear : attributions vides", M.Has("Bob", "kings"), false)
CHATCLEAR()
SlashCmdList["SHIKIUI"]("help")
CONTAINS("aide du module", CHATTEXT(), "/sui pp")
M.Close()

SECTION("t_pallypower : cout et coupure propre")
PP_BUFF("raid1", nil)
PP_BUFF("raid2", nil)
PP_BUFF("raid3", nil)
M.SetAll("kings", true)
PP_CLEARCASTS()
M.CastAll()
T("minuterie du cycle", M.task ~= nil)
local function liveTasks() local n = 0 for i = 1, table.getn(SUI.tasks) do if not SUI.tasks[i].dead then n = n + 1 end end return n end
local before = liveTasks()
C.Set("modules.pallypower", false)
EQ("module coupe", mod.enabled, false)
EQ("fenetre fermee", M.win:IsShown(), false)
EQ("minuterie rendue", liveTasks(), before - 1)
EQ("file rendue", M.npairs, 0)
EQ("evenements rendus", SUI.handlers["RAID_ROSTER_UPDATE"], nil)
C.Set("modules.pallypower", true)
SETTLE()
EQ("rallume", mod.enabled, true)
EQ("aucune erreur interne " .. tostring(SUI.lastErr), SUI.errCount, 0)
M.Stop()
DONE()
