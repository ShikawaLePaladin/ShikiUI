-- t_raid : module "raid" (cadres de raid 40 ultra legers, moteur partage SUI.GroupEngine) : contrat, construction, roster, tri par groupe,
-- budget, puissance coupee, alertes, aucun travail en combat, preset Raid, cycle de vie.
local SUI = ShikiUI
local C = SUI.Config
GRP_SETUP()
EXT.unitxp("real")
BOOT()
SETTLE()
local E = SUI.GroupEngine
local M = SUI.Raid

local function vis(g)
  local n = 0
  for i = 1, table.getn(g.frames) do if g.frames[i].vis then n = n + 1 end end
  return n
end

SECTION("t_raid : contrat et construction hors combat")
local mod = SUI.modules.raid
T("module enregistre", mod ~= nil)
EQ("cout declare", mod and mod.cost, "heavy")
T("coupe par defaut", not mod.enabled)
EQ("categorie 46", SUI.categories.raid, 46)
EQ("ligne pfUI relevee", table.concat(SUI.Migrate.MAP.raid, ","), "raid")
EQ("pas d'instance avant activation", M.g, nil)
W.combat = true
GRP_RAID(25)
local c0 = CREATED
C.Set("modules.raid", true)
EQ("combat : module actif", mod.enabled, true)
EQ("combat : aucune frame creee", CREATED, c0)
W.combat = false
Fire("PLAYER_REGEN_ENABLED")
SETTLE()
local g = M.g
EQ("instance creee", g ~= nil, true)
EQ("construit", g.built, true)
EQ("40 cadres", table.getn(g.frames), 40)
EQ("position par la mise en page", SUI.Layout.items["raid"].frame, g.container)
EQ("une seule minuterie de passage", GRP_TASKS("Raid.flush"), 1)
EQ("une seule minuterie lente", GRP_TASKS("Raid.slow"), 1)
EQ("aucune erreur interne", SUI.errCount, 0)

SECTION("t_raid : roster et tri par groupe")
Pump(0.3, 3)
EQ("25 joueurs visibles", vis(g), 25)
EQ("nom coupe a 6 (soi-meme)", g.frames[1].nameText:GetText(), "Shikiw")
EQ("raid2 : nom coupe a 6", g.frames[2].nameText:GetText(), "Raider")
EQ("cadres hors roster caches", g.frames[26]:IsShown(), false)
EQ("5 colonnes (une par groupe)", g.container:GetWidth(), 5 * 64 + 4 * 6)
EQ("groupe 1 : premiere colonne", g.frames[1].points[1][4], 0)
EQ("groupe 2 : deuxieme colonne", g.frames[6].points[1][4], 70)
EQ("groupe 5 : derniere colonne", g.frames[21].points[1][4], 280)
EQ("2e du groupe 1 : une ligne plus bas", g.frames[2].points[1][5], -29)
C.Set("raid.maxgroup", 2)
Pump(0.2, 3)
EQ("maxgroup 2 : 10 joueurs", vis(g), 10)
C.Set("raid.maxgroup", 8)
Pump(0.2, 3)
EQ("maxgroup 8 : 25 joueurs", vis(g), 25)
C.Set("raid.sort", "none")
C.Set("raid.perline", 5)
Pump(0.2, 3)
EQ("sans tri, vertical : 2e colonne de 5", g.frames[6].points[1][4], 65)
EQ("sans tri, vertical : en haut de la colonne", g.frames[6].points[1][5], 0)
C.Set("raid.sort", "group")
GRP_RAID(40)
Fire("RAID_ROSTER_UPDATE")
Pump(0.3, 4)
EQ("40 joueurs", vis(g), 40)
EQ("huit colonnes", g.container:GetWidth(), 8 * 64 + 7 * 6)
GRP_RAID(10)
Fire("RAID_ROSTER_UPDATE")
Pump(0.3, 3)
EQ("depart : 10 joueurs", vis(g), 10)

SECTION("t_raid : etat, puissance coupee, evenements")
EQ("puissance coupee : aucun evenement de mana ecoute", g.evOn.UNIT_MANA == true, false)
EQ("puissance : barre cachee", g.frames[2].pw:IsShown(), false)
W.units.raid2.hp = 1000
Fire("UNIT_HEALTH", "raid2")
EQ("un seul cadre en file", g.qn, 1)
Pump(0.1, 2)
EQ("texte : vie manquante", g.frames[2].hpText:GetText(), "-3.0k")
Fire("UNIT_HEALTH", "raid2")
Fire("UNIT_HEALTH", "party1")
EQ("evenement d'une autre unite ignore", g.qn, 1)
Pump(0.1, 2)
W.units.raid3.dead = true
Fire("UNIT_HEALTH", "raid3")
Pump(0.1, 2)
EQ("mort : etat", g.frames[3].statusText:GetText(), SUI.L("unit.dead"))
W.units.raid3.dead = nil
Fire("UNIT_HEALTH", "raid3")
Pump(0.1, 2)
W.units.raid4.dist = 80
Pump(0.5, 6)
EQ("hors de portee : estompe", g.frames[4]:GetAlpha(), 0.45)
W.units.raid4.dist = 5
Pump(0.5, 6)
EQ("a portee", g.frames[4]:GetAlpha(), 1)

SECTION("t_raid : budget et tour lent")
GRP_RAID(40)
Fire("RAID_ROSTER_UPDATE")
Pump(0.3, 6)
C.Set("raid.budget", 3)
Pump(0.3, 30)
for i = 1, 10 do Fire("UNIT_HEALTH", "raid" .. i) end
EQ("dix cadres en file", g.qn, 10)
Pump(0.1, 1)
EQ("budget 3 : sept restent", g.qn, 7)
Pump(0.1, 4)
EQ("file videe", g.qn, 0)
C.Set("raid.budget", 12)
Pump(0.3, 4)
local created = CREATED
W.combat = true
for i = 1, 40 do Fire("UNIT_HEALTH", "raid" .. i) end
Pump(0.1, 6)
Pump(0.5, 12)
EQ("combat : rien de cree", CREATED, created)
W.combat = false

SECTION("t_raid : debuffs, dissipation, alertes")
GRP_RAID(10)
Fire("RAID_ROSTER_UPDATE")
Pump(0.3, 4)
GRP_SPELLS({ { "Remove Curse", "" } })
Fire("SPELLS_CHANGED")
local f5 = g.frames[5]
W.units.raid5.debuffs = { { "Interface\\Icons\\Spell_Shadow_CurseOfTounges", 1, "Curse" }, { "Interface\\Icons\\Spell_Nature_Slow", 1, "Magic" } }
Fire("UNIT_AURA", "raid5")
Pump(0.1, 2)
EQ("dissipables seulement : une icone (malediction)", f5.dN, 1)
EQ("marque de dissipation", f5.dispelTx:IsShown(), true)
C.Set("raid.dispelonly", false)
Pump(0.1, 2)
EQ("tous les debuffs : deux icones", f5.dN, 2)
C.Set("raid.debuffs", 1)
Pump(0.1, 2)
EQ("une icone", f5.dN, 1)
C.Set("raid.debuffs", 0)
C.Set("raid.dispelmode", "off")
C.Set("raid.hots", 0)
Pump(0.1, 2)
EQ("rien a afficher : aura non ecoutee", g.evOn.UNIT_AURA == true, false)
local hooked = 0
local function hook() hooked = hooked + 1 end
E.OnAlert(hook)
SlashCmdList["SHIKIUI"]("raid alert add Spell_Nature_Slow")
EQ("liste raid", C.Get("raid.alertlist"), "Spell_Nature_Slow")
EQ("alertes : aura de nouveau ecoutee", g.evOn.UNIT_AURA, true)
Fire("UNIT_AURA", "raid5")
Pump(0.1, 2)
EQ("alerte de raid", f5.alertIcon:IsShown(), true)
EQ("crochet du futur DebuffAlert appele", hooked, 1)
EQ("autre cadre : aucune alerte", g.frames[6].alertIcon:IsShown(), false)
SlashCmdList["SHIKIUI"]("raid alert del Spell_Nature_Slow")
EQ("liste vide", C.Get("raid.alertlist"), "")
Pump(0.1, 2)
EQ("alerte retiree", f5.alertIcon:IsShown(), false)
E.OffAlert(hook)
C.Set("raid.dispelmode", "known")
C.Set("raid.debuffs", 2)
C.Set("raid.dispelonly", true)

SECTION("t_raid : roles, chef, marques, aggro")
SlashCmdList["SHIKIUI"]("raid role Raider2 t")
EQ("role enregistre", C.Get("raid.roles"), "Raider2:T")
C.Set("raid.roletag", true)
Pump(0.1, 3)
EQ("etiquette de role", g.frames[2].tagText:GetText(), SUI.L("msg.group.role.t"))
C.Set("raid.roletag", false)
C.Set("raid.sort", "role")
Pump(0.1, 3)
EQ("tri par role : le tank en tete", g.frames[2].points[1][5], 0)
C.Set("raid.sort", "group")
SlashCmdList["SHIKIUI"]("raid role Raider2 none")
W.units.raid3.mark = 4
Fire("RAID_TARGET_UPDATE")
EQ("marque", g.frames[3].mark:IsShown(), true)
W.units.raid3.mark = nil
Fire("RAID_TARGET_UPDATE")
W.units.raid1.leader = true
Fire("PARTY_LEADER_CHANGED")
Pump(0.1, 3)
EQ("chef de raid", g.frames[1].tagText:GetText(), "*")
MKTARGET({ name = "Boss", canAttack = true })
MKTOT({ name = "Raider3", guid = "0xGraid3" })
Pump(0.5, 6)
EQ("aggro de la cible de la cible", g.frames[3].aggro, true)
W.units.target, W.units.targettarget = nil, nil
Pump(0.5, 6)
CHATCLEAR()
SlashCmdList["SHIKIUI"]("raid")
CONTAINS("etat", CHATTEXT(), "10")

SECTION("t_raid : preset Raid et reglages")
C.Set("raid.width", 80)
Pump(0.1, 3)
EQ("largeur appliquee", g.frames[1]:GetWidth(), 80)
C.Set("raid.width", 64)
SUI.Mode.Set("raid", "manual")
EQ("preset Raid : un debuff", C.Get("raid.debuffs"), 1)
EQ("preset Raid : budget 16", C.Get("raid.budget"), 16)
SUI.Mode.Set("normal", "manual")
EQ("retour au Normal", C.Get("raid.budget"), 12)
C.Set("raid.powerheight", 4)
Pump(0.1, 3)
EQ("puissance reglee : evenements ecoutes", g.evOn.UNIT_MANA, true)
C.Set("raid.powerheight", 0)

SECTION("t_raid : reglages de mise en page et de texte en direct")
Pump(0.3, 3)
C.Set("raid.orient", "horizontal")
Pump(0.2, 3)
EQ("horizontal : 2e du groupe a droite du 1er", g.frames[2].points[1][4], 65)
EQ("horizontal : meme ligne", g.frames[2].points[1][5], 0)
C.Set("raid.orient", "vertical")
Pump(0.2, 3)
EQ("vertical : 2e du groupe sous le 1er", g.frames[2].points[1][5], -29)
C.Set("raid.namelen", 3)
Pump(0.2, 3)
EQ("nom coupe a 3", g.frames[2].nameText:GetText(), "Rai")
C.Set("raid.namelen", 6)
Pump(0.2, 3)
EQ("nom remis a 6", g.frames[2].nameText:GetText(), "Raider")
C.Set("raid.height", 40)
Pump(0.2, 3)
EQ("hauteur appliquee", g.frames[1]:GetHeight(), 40)
C.Set("raid.height", 28)
Pump(0.2, 3)
C.Set("raid.iconsize", 14)
Pump(0.2, 3)
EQ("taille des icones appliquee", g.frames[1].mark:GetWidth(), 14)
C.Set("raid.iconsize", 10)
Pump(0.2, 3)
W.units.raid2.dist = 90
Pump(0.25, 3)
EQ("raid : hors de portee estompe", g.frames[2]:GetAlpha(), 0.45)
C.Set("raid.outalpha", 0.3)
EQ("raid : opacite appliquee tout de suite", g.frames[2]:GetAlpha(), 0.3)
C.Set("raid.outalpha", 0.45)
C.Set("raid.range", false)
EQ("raid : portee coupee tout de suite", g.frames[2]:GetAlpha(), 1)
C.Set("raid.range", true)
W.units.raid2.dist = 10
Pump(0.25, 3)

SECTION("t_raid : desactivation, reactivation")
C.Set("modules.raid", false)
EQ("module coupe", mod.enabled, false)
EQ("conteneur cache", g.container:IsShown(), false)
EQ("minuteries rendues", GRP_TASKS("Raid.flush") + GRP_TASKS("Raid.slow"), 0)
local any = false
for ev, v in pairs(g.evOn) do if v then any = true end end
EQ("plus aucun evenement", any, false)
local e0 = SUI.errCount
Fire("UNIT_HEALTH", "raid2")
Pump(0.5, 3)
EQ("coupe : rien ne tourne", SUI.errCount, e0)
C.Set("modules.raid", true)
Pump(0.3, 4)
EQ("rallume", vis(g) > 0, true)
EQ("minuteries de retour", GRP_TASKS("Raid.flush") + GRP_TASKS("Raid.slow"), 2)
EQ("aucune erreur interne", SUI.errCount, 0)
DONE()
