SECTION("t_skin : objets sans nom ni methodes de cadre")
do
  local M = SUI.Skin
  local n0 = SUI.errCount or 0
  M.AddHide({}, "tooltips")                                                 -- table nue
  M.AddHide({ Hide = function() end, IsShown = function() return 1 end }, "tooltips")  -- pseudo-region sans GetObjectType
