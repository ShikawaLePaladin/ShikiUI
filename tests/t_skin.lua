-- une erreur interne venue d'un autre module (tache differee) ne doit pas faire echouer cette suite
local function skinErr() return SUI.lastErr ~= nil and string.find(SUI.lastErr, "skin", 1, true) ~= nil end

-- ---------------------------------------------------------------- monde : quelques cadres Blizzard simules
local function world()
  -- menu Echap : decor, titre, deux boutons de panneau
  local gm = SKIN_FRAME("GameMenuFrame", "Frame")
  gm.art = SKIN_TEX(gm, "GameMenuFrameTopLeft", "Interface\\DialogFrame\\UI-DialogBox-Header")
  gm.ico = SKIN_TEX(gm, "GameMenuFrameIcon", "Interface\\Icons\\X")
  gm.title = SKIN_FS(gm, nil, 14)
  gm.b1 = SKIN_BTN("GameMenuButtonOptions", gm, "Options")
  gm.b2 = SKIN_BTN("GameMenuButtonContinue", gm, "Retour")
  gm.arrow = SKIN_BTN("GameMenuScrollUpButton", gm, "^")        -- exclu : fleche
  local oldShow = 0
  gm:SetScript("OnShow", function() oldShow = oldShow + 1 end)
  gm.oldShowCount = function() return oldShow end
  -- personnage : decor, onglet, case d'objet, barre de defilement, modele 3D
  local cf = SKIN_FRAME("CharacterFrame", "Frame")
  cf.art = SKIN_TEX(cf, "CharacterFramePortrait", "Interface\\X")
  cf.t1 = SKIN_BTN("CharacterFrameTab1", cf, "Personnage")
  cf.t2 = SKIN_BTN("CharacterFrameTab2", cf, "Reputation")
  cf.slot = SKIN_SLOT("CharacterHeadSlot", cf)
  cf.slot2 = SKIN_SLOT("CharacterNeckSlot", cf, "Interface\\Icons\\INV_Misc_Neck")
  cf.sb = SKIN_SCROLL("ReputationListScrollFrameScrollBar", cf)
  cf.model = SKIN_FRAME("CharacterModelFrame", "Model", cf)
  cf.close = SKIN_BTN("CharacterFrameCloseButton", cf, "")
  cf.close:SetWidth(32)
  -- listes deroulantes : cadres de decor avec leur propre Backdrop
  for i = 1, 3 do
    local dd = SKIN_FRAME("DropDownList" .. i, "Button")
    SKIN_FRAME("DropDownList" .. i .. "Backdrop", "Frame", dd)
    SKIN_FRAME("DropDownList" .. i .. "MenuBackdrop", "Frame", dd)
  end
  -- fenetre de confirmation
  local sp = SKIN_FRAME("StaticPopup1", "Frame")
  sp.b1 = SKIN_BTN("StaticPopup1Button1", sp, "Oui")
  -- carte du monde : tuile + liste
  local wm = SKIN_FRAME("WorldMapFrame", "Frame")
  wm.tile = SKIN_TEX(wm, "WorldMapTile1", "Interface\\WorldMap\\X")
  wm.dd = SKIN_FRAME("WorldMapContinentDropDown", "Frame", wm)
  wm.dd.left = SKIN_TEX(wm.dd, "WorldMapContinentDropDownLeft", "Interface\\Glues\\X")
  -- parchemin
  local ql = SKIN_FRAME("QuestLogFrame", "Frame")
  ql.paper = SKIN_TEX(ql, "QuestLogFrameTopLeft", "Interface\\QuestFrame\\X")
  ql.txt = SKIN_FS(ql, "QuestLogQuestDescription", 12)
  -- courrier (pfUI le habille)
  local mf = SKIN_FRAME("MailFrame", "Frame")
  mf.art = SKIN_TEX(mf, "MailFrameTopLeft", "Interface\\X")
  -- options Blizzard : panneau de section frere des cases a cocher
  local of = SKIN_FRAME("OptionsFrame", "Frame")
  SKIN_FRAME("OptionsFrameDisplay", "Frame", of)
  SKIN_FRAME("OptionsFrameCheckButton1", "CheckButton", of):SetWidth(24)
  -- carte des vols : jamais de decor
  local tx = SKIN_FRAME("TaxiFrame", "Frame")
  tx.map = SKIN_TEX(tx, "TaxiMap", "Interface\\TaxiFrame\\X")
  -- dressup : modele
  local du = SKIN_FRAME("DressUpFrame", "Frame")
  du.art = SKIN_TEX(du, "DressUpFrameTopLeft", "Interface\\X")
  du.model = SKIN_FRAME("DressUpModel", "Model", du)
end
world()

