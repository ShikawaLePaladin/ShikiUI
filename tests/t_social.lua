local function hasHandler(ev, fn)
  local h = SUI.handlers[ev]
  if not h then return false end
  for i = 1, table.getn(h) do if h[i] == fn then return true end end
  return false
end
local function liveTasks(name)
  local n = 0
  for i = 1, table.getn(SUI.tasks) do
    if SUI.tasks[i].name == name and not SUI.tasks[i].dead then n = n + 1 end
  end
  return n
end
local EVENTS = { "CHAT_MSG_WHISPER", "CHAT_MSG_GUILD", "UPDATE_MOUSEOVER_UNIT", "PLAYER_TARGET_CHANGED", "PARTY_MEMBERS_CHANGED",
  "RAID_ROSTER_UPDATE", "PARTY_LEADER_CHANGED", "PARTY_INVITE_REQUEST", "DUEL_REQUESTED", "GUILD_INVITE_REQUEST",
  "CONFIRM_SUMMON", "RESURRECT_REQUEST" }
local function mine(ev)
  local h = SUI.handlers[ev]
  if not h then return false end
  local fns = { M.OnChat, M.OnMouse, M.OnTarget, M.UpdateCan, M.OnPartyInvite, M.OnDuel, M.OnGuildInvite, M.OnSummon, M.OnRez }
  for i = 1, table.getn(h) do
    for j = 1, table.getn(fns) do if h[i] == fns[j] then return true end end
  end
  return false
end
