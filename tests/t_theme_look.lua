-- t_theme_look : briques communes de Theme.lua : bouton engrenage (T.GearButton / T.GearLevel) et aspect par module
-- (T.AssetFor / T.BarTexture / T.Font, SUI.Look.Options / ApplyBar / ApplyText).
local SUI = ShikiUI
local C = SUI.Config
local TH = SUI.Theme
local Look = SUI.Look

BOOT()
SETTLE()
W.combat = false
if not GameTooltip then GameTooltip = CreateFrame("GameTooltip", "GameTooltip") end

SECTION("t_theme_look : bouton engrenage")
local P = CreateFrame("Frame")
local oldShown = 0
P:SetScript("OnShow", function() oldShown = oldShown + 1 end)
P:SetFrameLevel(5)
local sib = CreateFrame("Frame", nil, P)
sib:SetFrameLevel(7)
local grand = CreateFrame("Frame", nil, sib)
grand:SetFrameLevel(12)
local created
local btn = TH.GearButton(P, "meter", { onCreate = function(b) created = b end })
T("bouton cree", btn ~= nil)
EQ("rappel onCreate", created, btn)
EQ("parent memorise", btn.suiGearParent, P)
EQ("categorie memorisee", btn.gearCat, "meter")
T("niveau au-dessus du contenu (12 + 2)", btn:GetFrameLevel() >= 14)
EQ("meme strate que le parent", btn.calls.SetFrameStrata[1], P)
EQ("glyphe texte", btn.label:GetText(), "o")
EQ("ancre par defaut", btn.points[1][1], "TOPRIGHT")
EQ("taille", btn:GetWidth(), 16)
-- le client change les niveaux apres la construction
sib:SetFrameLevel(40)
grand:SetFrameLevel(47)
P:Hide()
P:Show()
EQ("ancien OnShow conserve", oldShown, 1)
T("recale a l'affichage (47 + 2)", btn:GetFrameLevel() >= 49)
grand:SetFrameLevel(70)
Pump(0.2)
T("pas encore recale avant 0,3 s", btn:GetFrameLevel() < 72)
Pump(0.2)
T("recale par le rappel differe", btn:GetFrameLevel() >= 72)
btn:SetFrameLevel(1)
TH.GearLevel(btn)
T("GearLevel recale a la demande", btn:GetFrameLevel() >= 72)
TH.GearLevel(nil)
TH.GearLevel(CreateFrame("Frame"))
-- un second bouton sur le meme parent : un seul crochet
local btn2 = TH.GearButton(P, "threat", { size = 12, point = "TOPLEFT", x = 2, y = -2, title = "Titre" })
EQ("taille 12", btn2:GetWidth(), 12)
EQ("deux boutons suivis", table.getn(P.suiGears), 2)
oldShown = 0
P:Hide()
P:Show()
EQ("ancien OnShow appele une seule fois", oldShown, 1)

SECTION("t_theme_look : engrenage - infobulle et clics")
Hover(btn, true)
EQ("infobulle ancree au bouton", GameTooltip.owner, btn)
EQ("titre FR", GameTooltip.lines[1], "Reglages de ce module")
CONTAINS("rappel de la commande", GameTooltip.lines[2], "/sui menu meter")
Hover(btn, false)
EQ("infobulle masquee", GameTooltip:IsShown(), false)
Hover(btn2, true)
EQ("titre fourni par le module", GameTooltip.lines[1], "Titre")
Hover(btn2, false)
SUI.SetLocale("en")
Hover(btn, true)
EQ("titre EN", GameTooltip.lines[1], "Settings for this module")
Hover(btn, false)
SUI.SetLocale("fr")
local shown
local keepShow = SUI.Menu.Show
SUI.Menu.Show = function(arg) shown = arg end
Click(btn)
EQ("clic gauche : page du module", shown, "meter")
shown = nil
Click(btn, "RightButton")
EQ("clic droit sans action : page du module", shown, "meter")
local rc
local b3 = TH.GearButton(P, "loot", { onRight = function(b) rc = b end })
shown = nil
Click(b3, "RightButton")
EQ("clic droit : action du module", rc, b3)
EQ("clic droit : pas de menu", shown, nil)
Click(b3, "LeftButton")
EQ("clic gauche : page loot", shown, "loot")
SUI.Menu.Show = keepShow
Click(btn2)
EQ("menu reel : page de categorie", SUI.Menu.page, "cat")
EQ("menu reel : categorie visee", SUI.Menu.cat, "threat")
SUI.Menu.Hide()

SECTION("t_theme_look : engrenage - texture du style et combat")
TH.tex.gear = "style\\gear"
local bt = TH.GearButton(P, "meter", {})
T("texture d'engrenage du style", bt.icon ~= nil)
EQ("texture posee", bt.icon.calls.SetTexture[1], "style\\gear")
EQ("glyphe masque", bt.label:IsShown(), false)
TH.tex.gear = nil
EQ("pas d'engrenage par defaut", TH.tex.gear, nil)
W.combat = true
local cc = CREATED
local late
local rb = TH.GearButton(P, "meter", { onCreate = function(b) late = b end })
EQ("en combat : rien retourne", rb, nil)
EQ("en combat : rien cree", CREATED, cc)
W.combat = false
Fire("PLAYER_REGEN_ENABLED")
T("sortie de combat : bouton cree", late ~= nil)
EQ("argument invalide", TH.GearButton(nil, "meter"), nil)
EQ("categorie invalide", TH.GearButton(P, nil), nil)

SECTION("t_theme_look : options communes")
local o = Look.Options("lk", { bar = true, font = true, shape = true })
EQ("quatre descripteurs", table.getn(o), 4)
EQ("bartex", o[1].key, "lk.bartex")
EQ("shape", o[2].key, "lk.shape")
EQ("font", o[3].key, "lk.font")
EQ("fontsize", o[4].key, "lk.fontsize")
EQ("defaut bartex : style", o[1].default, "style")
EQ("defaut shape : style", o[2].default, "style")
EQ("defaut police : style", o[3].default, "style")
EQ("defaut taille : 0", o[4].default, 0)
EQ("categorie deduite", o[1].cat, "lk")
EQ("liste des textures = celle du style", o[1].choices, C.meta["style.bartex"].choices)
EQ("liste des polices = celle du style", o[3].choices, C.meta["style.font"].choices)
EQ("formes", table.getn(o[2].choices), 5)
EQ("une seule famille", table.getn(Look.Options("lk2", { bar = true })), 1)
EQ("rien demande", table.getn(Look.Options("lk3", {})), 0)
EQ("sans parametre", table.getn(Look.Options("lk3")), 0)
EQ("categorie imposee", Look.Options("lk4.sub", { bar = true, cat = "meter" })[1].cat, "meter")
EQ("texte du defaut", o[1].choiceText(o[1], "style"), "Defaut du style")
EQ("texte d'une texture connue", o[1].choiceText(o[1], "flat"), SUI.L("choice.style.bartex.flat"))
EQ("texte d'une forme", o[2].choiceText(o[2], "segmented"), "Segmente")
SUI.SetLocale("en")
EQ("forme EN", o[2].choiceText(o[2], "thin"), "Thin")
SUI.SetLocale("fr")
T("libelles traduits", SUI.L(o[1].label) ~= o[1].label and SUI.L(o[2].tip) ~= o[2].tip and SUI.L(o[4].label) ~= o[4].label)
for i = 1, 4 do SUI.RegisterOption(o[i]) end
EQ("shape invalide refuse", C.Set("lk.shape", "carre"), false)
EQ("shape reste", C.Get("lk.shape"), "style")
-- ressource ajoutee par l'utilisateur : proposee sans rien refaire
local okAsset = SUI.RegisterAsset("bar", "lkmine", "Interface\\AddOns\\MesMedias\\barre.tga")
EQ("ressource enregistree", okAsset, true)
local found = false
for i = 1, table.getn(o[1].choices) do if o[1].choices[i] == "lkmine" then found = true end end
EQ("la ressource apparait dans la liste du module", found, true)

SECTION("t_theme_look : lecture des ressources")
EQ("defaut : texture du style", TH.AssetFor("bar", "lk"), TH.barTex)
EQ("defaut : police du style", TH.AssetFor("font", "lk"), TH.font)
EQ("BarTexture", TH.BarTexture("lk"), TH.barTex)
EQ("prefixe sans reglage", TH.BarTexture("nonedeclare"), TH.barTex)
EQ("genre inconnu", TH.AssetFor("panel", "lk"), nil)
local fp, fs0 = TH.Font("lk")
EQ("police par defaut", fp, TH.font)
EQ("taille par defaut : celle du module", fs0, nil)
C.Set("lk.bartex", "blizzard")
EQ("texture choisie", TH.BarTexture("lk"), TH.BARS.blizzard)
C.Set("lk.bartex", "lkmine")
EQ("texture utilisateur", TH.BarTexture("lk"), "Interface\\AddOns\\MesMedias\\barre.tga")
SUI.Style.missing["bar:lkmine"] = true
EQ("texture absente : repli sur le style", TH.BarTexture("lk"), TH.barTex)
SUI.Style.missing["bar:lkmine"] = nil
C.Set("lk.font", "frizqt")
C.Set("lk.fontsize", 14)
fp, fs0 = TH.Font("lk")
EQ("police choisie", fp, TH.FONTS.frizqt)
EQ("taille choisie", fs0, 14)
C.Set("lk.fontsize", 0)
fp, fs0 = TH.Font("lk")
EQ("taille 0 = module", fs0, nil)
C.Set("lk.font", "style")
C.Set("lk.bartex", "style")

SECTION("t_theme_look : formes de barre")
local bar = TH.Bar(P)
bar:SetHeight(10)
bar:SetWidth(100)
Look.ApplyBar(bar, "lk")
EQ("texture du style", bar.calls.SetStatusBarTexture[1], TH.barTex)
EQ("hauteur inchangee", bar:GetHeight(), 10)
EQ("pas de degrade", bar.suiGrad, nil)
EQ("pas de segments", bar.suiSegs, nil)
C.Set("lk.bartex", "blizzard")
EQ("changement de reglage : repeint seul", bar.calls.SetStatusBarTexture[1], TH.BARS.blizzard)
C.Set("lk.shape", "thin")
EQ("fin : hauteur reduite (40 %)", bar:GetHeight(), 4)
C.Set("lk.shape", "plain")
EQ("plein : hauteur rendue", bar:GetHeight(), 10)
C.Set("lk.shape", "gradient")
T("degrade cree", bar.suiGrad ~= nil)
EQ("degrade affiche", bar.suiGrad:IsShown(), true)
EQ("degrade vertical", bar.suiGrad.calls.SetGradientAlpha[1], "VERTICAL")
EQ("couleur du degrade = jeton", bar.suiGrad.calls.SetGradientAlpha[2], TH.c.inset[1])
C.Set("lk.shape", "segmented")
EQ("degrade masque", bar.suiGrad:IsShown(), false)
EQ("neuf separateurs (10 segments)", table.getn(bar.suiSegs), 9)
EQ("separateur 1 a 10 %", bar.suiSegs[1].points[1][4], 10)
EQ("separateur 5 a 50 %", bar.suiSegs[5].points[1][4], 50)
EQ("separateur affiche", bar.suiSegs[3]:IsShown(), true)
EQ("couleur du separateur = jeton", bar.suiSegs[1].vc[1], TH.c.bg[1])
Look.ApplyBar(bar, "lk", { segments = 4 })
EQ("4 segments : separateur 2 a 50 %", bar.suiSegs[2].points[1][4], 50)
EQ("4 segments : separateur 3 affiche", bar.suiSegs[3]:IsShown(), true)
EQ("4 segments : separateur 4 masque", bar.suiSegs[4]:IsShown(), false)
Look.ApplyBar(bar, "lk", {})
C.Set("lk.shape", "style")
EQ("retour au style : separateurs masques", bar.suiSegs[1]:IsShown(), false)
EQ("retour au style : hauteur", bar:GetHeight(), 10)
-- hauteur fournie par le module, forme fine imposee
Look.ApplyBar(bar, "lk", { height = 20, thin = 3 })
C.Set("lk.shape", "thin")
EQ("hauteur fine imposee", bar:GetHeight(), 3)
C.Set("lk.shape", "style")
EQ("hauteur du module", bar:GetHeight(), 20)
-- le style change : le reglage du module passe par-dessus
C.Set("lk.bartex", "blizzard")
bar:SetStatusBarTexture("autre")
TH.Restyle()
EQ("apres Restyle : texture du module", bar.calls.SetStatusBarTexture[1], TH.BARS.blizzard)
-- largeur inconnue : pas de separateurs poses
local nb = TH.Bar(P)
nb:SetHeight(8)
C.Set("lk.shape", "segmented")
Look.ApplyBar(nb, "lk")
EQ("largeur 0 : separateurs masques", nb.suiSegs[1]:IsShown(), false)
nb:SetWidth(50)
Look.ApplyBar(nb, "lk")
EQ("largeur connue : separateurs places", nb.suiSegs[1].points[1][4], 5)

SECTION("t_theme_look : aucune creation en combat")
local cb = TH.Bar(P)
cb:SetHeight(10)
cb:SetWidth(100)
C.Set("lk.shape", "style")
Look.ApplyBar(cb, "lk")
W.combat = true
local c4 = CREATED
C.Set("lk.shape", "gradient")
EQ("degrade non cree en combat", cb.suiGrad, nil)
C.Set("lk.shape", "segmented")
EQ("segments non crees en combat", cb.suiSegs ~= nil and table.getn(cb.suiSegs) or 0, 0)
C.Set("lk.bartex", "flat")
EQ("la texture, elle, suit tout de suite", cb.calls.SetStatusBarTexture[1], TH.BARS.flat)
EQ("rien cree", CREATED, c4)
W.combat = false
Fire("PLAYER_REGEN_ENABLED")
EQ("sortie de combat : segments crees", table.getn(cb.suiSegs), 9)
T("sortie de combat : separateurs poses", cb.suiSegs[1]:IsShown())
C.Set("lk.shape", "style")

SECTION("t_theme_look : textes")
local txt = TH.Text(P, 11)
Look.ApplyText(txt, "lk", 11)
EQ("police du style", txt.font, TH.font)
EQ("taille du module (x echelle)", txt.fsize, math.floor(11 * TH.fontScale + 0.5))
C.Set("lk.font", "frizqt")
EQ("police choisie", txt.font, TH.FONTS.frizqt)
C.Set("lk.fontsize", 15)
EQ("taille choisie", txt.fsize, 15)
TH.Restyle()
EQ("apres Restyle : police du module", txt.font, TH.FONTS.frizqt)
EQ("apres Restyle : taille du module", txt.fsize, 15)
C.Set("lk.fontsize", 0)
C.Set("lk.font", "style")
EQ("retour : police du style", txt.font, TH.font)
Look.ApplyText(txt, "lk", 11, true)
EQ("contour demande", txt.fflags, "OUTLINE")
Look.Forget(txt)
C.Set("lk.font", "frizqt")
EQ("oublie : plus repeint", txt.font, TH.font)
C.Set("lk.font", "style")
Look.ApplyText(nil, "lk", 11)
Look.ApplyBar(nil, "lk")
Look.ApplyText(txt, nil, 11)

SECTION("t_theme_look : style et lecture sans configuration")
C.Set("lk.bartex", "style")
C.Set("style.bartex", "blizzard")
Pump(0.5, 4)
EQ("sans reglage de module : suit le style", TH.BarTexture("lk"), TH.barTex)
C.Set("style.bartex", "style")
EQ("aucune erreur", SUI.errCount, 0)

DONE()
