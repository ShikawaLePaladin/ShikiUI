local bad = 0
local function scan(t, depth)
  if depth > 6 then return end
  for k, v in pairs(t) do
    local ty = type(v)
    if ty == "function" or ty == "userdata" then bad = bad + 1 end
    if ty == "table" then
      if v.GetObjectType then bad = bad + 1 else scan(v, depth + 1) end
    end
  end
end
scan(ShikiUIDB.global.tracker, 0)
EQ("aucune fonction ni frame dans la base", bad, 0)

