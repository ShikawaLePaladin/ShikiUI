local realInfo, realLink = GetContainerItemInfo, GetContainerItemLink
GetContainerItemInfo = function(bag, slot)
  local tex, count, locked = realInfo(bag, slot)
  return tex, count, locked, nil
end
GetContainerItemLink = function(bag, slot)
  local l = realLink(bag, slot)
  if not l then return nil end
  if string.find(l, "Hitem:1:", 1, true) then return string.gsub(l, "|cffffffff", "|cff9d9d9d") end
  return l
end
